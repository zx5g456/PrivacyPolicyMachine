from config import XR_DATA_TYPES


def construct_data_type_prompt(policy_text, filename):
    """
    The prompt focuses on XR-specific data collection, privacy concerns, and compliance requirements.
    """

    # Main tasks prompt specifically for XR applications
    main_prompt = (
        "CRITICAL INSTRUCTIONS: You are analyzing privacy policies from confirmed XR (Extended Reality) applications. "
        "Be EXTREMELY CONSERVATIVE and ACCURATE in your analysis - only report data collection practices that are "
        "EXPLICITLY MENTIONED in the privacy policy text.\n\n"
        "XR DATA ANALYSIS CATEGORIES:\n"
        "For each category below, provide detailed analysis with SOURCE CITATIONS. "
        "ONLY include data types that are EXPLICITLY MENTIONED or CLEARLY IMPLIED in the privacy policy text. "
        "For each identified data type, quote the specific text from the policy that supports your identification.\n\n"
        "XR_DATA_TYPES (Complete XR-related data collection): "
        "List all XR data types that are EXPLICITLY mentioned in the privacy policy.\n"
        "STRICT REQUIREMENT: Include ONLY data types where you can find the EXACT PHRASE.\n"
        f"Search for these {len(XR_DATA_TYPES)} specific terms exactly as written.\n\n"
        "EXAMPLES:\n"
        "✓ If policy contains 'virtual reality tracking data' → include it\n"
        "✓ If policy contains 'heart rate data' → include it\n"
        "✗ If policy only has 'heart rate monitoring' → do NOT include 'heart rate data'\n"
        "✗ If policy only has 'location information' → do NOT include 'location tracking data'\n\n"
        "FORMAT: [data_type1, data_type2, data_type3] or [NONE] if no exact matches\n\n"
        "CHILDREN_XR (Age-specific data collection policies for XR): "
        "Report ONLY if there are specific mentions of children in XR context. "
        "Format as 'age boundary: {age}, special considerations: {details}' or 'NONE' if not mentioned.\n"
        "SOURCE EVIDENCE: Quote the text that mentions children or age restrictions.\n\n"
        "REGION_XR (Regional-specific XR policies): "
        "Report ONLY if there are XR-specific regional policies mentioned. "
        "Format as '{region}: {XR_policy_details}' or 'NONE' if no XR-specific regional policies.\n"
        "SOURCE EVIDENCE: Quote the text that mentions regional differences.\n\n"
        "RETENTION_XR (XR data retention period): "
        "Report ONLY if XR-specific data retention is mentioned. "
        "Format as '{data_type}: {retention_period}' or 'NONE' if not specified.\n"
        "SOURCE EVIDENCE: Quote the text that mentions data retention periods.\n\n"
        "SHARING_XR (Third-party data sharing for XR data): "
        "Report ONLY if XR-specific data sharing is mentioned. "
        "Format as '{recipient}: {XR_data_types_shared}' or 'NONE' if not mentioned.\n"
        "SOURCE EVIDENCE: Quote the text that mentions third-party data sharing.\n\n"
    )

    # XR-specific data type checklist
    xr_type_check_prompt = (
        "XR_TYPE_CHECKLIST:\n"
        "EXTREMELY CRITICAL: Only mark '1' if you can find the EXACT TERM or clear synonym in the policy text.\n"
        "DO NOT mark '1' based on assumptions, inferences, or general descriptions.\n\n"
        f"REQUIRED: You MUST provide EXACTLY {len(XR_DATA_TYPES)} values in your checklist array.\n\n"
        "ULTRA-STRICT MATCHING RULES:\n"
        "Mark '1' ONLY if:\n"
        "- You can find the EXACT term in the policy text\n"
        "- OR you can find a clear synonym (e.g., 'heart rate monitor' for 'heart rate data')\n"
        "- You can quote the specific sentence that contains this term\n\n"
        "Mark '0' in ALL other cases:\n"
        "- Generic terms like 'biometric data', 'device information', 'usage data'\n"
        "- Vague descriptions that might include the data type\n"
        "- Any assumption or inference you might make\n"
        "- If you cannot find the specific term in the text\n\n"
        "DATA TYPES TO CHECK (mark 1 ONLY if found in policy text):\n"
        f"{chr(10).join([f'{i+1:2d}. {dtype}' for i, dtype in enumerate(XR_DATA_TYPES)])}\n\n"
        f"Provide EXACTLY {len(XR_DATA_TYPES)} values (1 or 0):\n"
        "[0, 0, 1, 0, 1, ...]  (example format)\n\n"
        "JUSTIFICATION (ONLY for values marked as '1'):\n"
        "For each '1', provide:\n"
        "- Data type name and position\n"
        "- EXACT quote from policy that contains this specific term\n"
        "- Why this quote clearly indicates collection of this data type\n\n"
        "REMEMBER: When in doubt, mark '0'. Be extremely conservative.\n\n"
    )

    # Combine policy text with XR-specific instructions
    prompt = (
        f"XR PRIVACY POLICY ANALYSIS - CONSERVATIVE APPROACH\n"
        f"==================================================\n\n"
        f"File being analyzed: {filename}\n\n"
        f"MISSION: Extract ONLY explicitly mentioned XR data collection practices from this confirmed XR application privacy policy.\n\n"
        f"REQUIRED OUTPUT SECTIONS:\n"
        f"You MUST provide ALL of these sections in your response:\n\n"
        f"{main_prompt}\n\n"
        f"{xr_type_check_prompt}\n\n"
        f"Privacy Policy Text to Analyze:\n"
        f"{'='*50}\n"
        f"{policy_text}\n"
        f"{'='*50}\n\n"
        f"CRITICAL OUTPUT FORMAT:\n"
        f"Your response must include these EXACT section headers:\n"
        f"- XR_DATA_TYPES: [list or NONE]\n"
        f"- XR_TYPE_CHECKLIST: [{len(XR_DATA_TYPES)} values of 0 or 1]\n"
        f"- CHILDREN_XR: [content or NONE]\n"
        f"- REGION_XR: [content or NONE]\n"
        f"- RETENTION_XR: [content or NONE]\n"
        f"- SHARING_XR: [content or NONE]\n"
        f"- JUSTIFICATION: [explanations for checklist 1s]\n\n"
        f"FINAL REMINDER:\n"
        f"- Be conservative and only report what is explicitly mentioned\n"
        f"- Do NOT assume or infer data collection practices beyond what is clearly stated\n"
        f"- When uncertain, err on the side of marking data as NOT collected (0 in checklist)\n"
        f"- Focus on factual accuracy over comprehensive coverage\n"
        f"- Use [NONE] for categories where no relevant data is explicitly mentioned"
    )

    return prompt
